# Imports the required libraries in the code

import json
import time
from getpass import getpass
from google import genai
 
# Uses getpass library which protects the info entered

api_key = getpass("Gemini API Key: ")

# This code reads questions from text.txt, stores them in a list, and prints each question separately.

with open("text.txt", "r", encoding ="utf-8") as file:
  questions =[]
  for line in file:
    question = line.strip()
    if question:
      questions.append(question)

# The actual API call for each question andthe response is stored in responses after every iteration.

responses =[]
client = genai.Client(api_key = api_key)

for question in questions:
  response = client.interactions.create(
      model = "gemini-3.5-flash-lite",
      input = question
      )
  responses.append({
    "Question: ": question,
    "Answer: ": response.output_text
    })
  print("\nQuestion: ", question)
  print("Answer: ",response.output_text)
  time.sleep(20)   # Adds a time delay so that the rate limit of API calls is not hit

# Creates a json file to store the questions and responses generated by the code

with open("responses.json","w", encoding="utf-8") as file:
  json.dump(responses, file, indent=2)

print("Answers Saved: ", len(responses))
